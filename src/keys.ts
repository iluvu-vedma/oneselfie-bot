/**
 * Карта ключей KV. Отдельным модулем, потому что `kv.ts` при импорте создаёт
 * клиент Redis и падает без переменных окружения, а ключи нужны и проверочным
 * скриптам с заглушкой вместо базы. Копировать карту руками нельзя: новый ключ
 * в боте и старая копия в скрипте расходятся молча.
 */

// ── Ключи ────────────────────────────────────────────────────────────────────
export const k = {
  /** Профиль: status, name, username, model, source, topupFrom, fails, createdAt. Баланса тут НЕТ. */
  user: (chatId: number | string) => `user:${chatId}`,
  /**
   * Баланс искр отдельным ключом-числом.
   * Только INCRBY/DECRBY — «прочитал объект, изменил поле, записал» ломается
   * на двух быстрых тапах.
   */
  balance: (chatId: number | string) => `bal:${chatId}`,
  /** Список URL селфи после заливки в kie. */
  photos: (chatId: number | string) => `photos:${chatId}`,
  /** Счётчик занятых слотов под селфи. Резервируется до загрузки. */
  photoSlots: (chatId: number | string) => `photoslots:${chatId}`,
  /** Замок «кадр уже готовится». Один тап — один кадр. */
  genLock: (chatId: number | string) => `gen:${chatId}`,
  /**
   * Замок на обработку апдейтов одного чата. На serverless апдейты одного
   * человека приезжают в разные процессы одновременно — альбом из четырёх селфи
   * это четыре параллельных запуска, — и внутрипроцессный `sequentialize`
   * из grammY там не работает вовсе. Очередь держится в KV, потому что она
   * общая для всех процессов.
   */
  chatLock: (chatId: number | string) => `lock:${chatId}`,
  /**
   * message_id экрана. Весь интерфейс живёт в одном сообщении и редактируется;
   * без этого ключа бот не знает, что именно перерисовывать.
   */
  hub: (chatId: number | string) => `hub:${chatId}`,
  /** Задача генерации. */
  task: (taskId: string) => `task:${taskId}`,
  /**
   * Какую задачу ждёт этот человек. Индекс в обратную сторону: `pending` знает
   * все задачи, но по чату из него не выбрать, а добор по действию человека
   * должен стоить один чтение, а не обход всего множества.
   */
  chatTask: (chatId: number | string) => `chattask:${chatId}`,
  /** Отметка обработанного платежа, чтобы искры не зачислились дважды. */
  payment: (chargeId: string) => `pay:${chargeId}`,
  /** Индекс незавершённых задач для аварийного добора: score = createdAt (мс). */
  pending: "pending",
  /** Счётчик события за всё время. */
  stat: (event: string) => `stat:${event}`,
  /** Счётчик события за один день. Дашборд без «сегодня» ничего не показывает. */
  statDay: (event: string, day: string) => `stat:${event}:${day}`,

  // ── Админка ────────────────────────────────────────────────────────────────
  /**
   * История операций человека: новые сверху, хвост подрезается.
   * Баланс — счётчик, из него не видно, откуда взялось число; лог видит.
   */
  ledger: (chatId: number | string) => `led:${chatId}`,
  /** Общий лог сбоев генераций. Отсюда админка узнаёт, кому положена компенсация. */
  fails: "fails",
  /** Личный лог сбоев. Нужен карточке: из общего человек может уже вымыться. */
  userFails: (chatId: number | string) => `fl:${chatId}`,
  /** Лог ручных начислений: кто, когда, кому, сколько и почему. */
  grants: "grants",
  /**
   * Кольцо последних ошибок. Логи Vercel живут час на бесплатном тарифе,
   * а вопрос «что у нас сломалось» задают на следующий день — поэтому свои.
   */
  errors: "errors",
  /** Индекс людей: score = createdAt (мс). Без него «последние люди» неоткуда взять. */
  users: "users",
  /** @username → chat_id. У Bot API такого метода нет, индекс только свой. */
  uname: (username: string) => `un:${username.toLowerCase()}`,
  /** Состояние админа: кого смотрим, чего ждём от него текстом, куда вернёт «Назад». */
  admin: (chatId: number | string) => `adm:${chatId}`,
};
